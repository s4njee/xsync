        "is pure bandwidth, both tools sit at line rate, and there is nothing",
        "there to win.",
        "",
        "The pattern is that xsync's lead grows with **per-file overhead** and",
        "with **receiver weakness**, not with raw bandwidth:",
        "",
        "- `congress` is ~1.9-2.2x everywhere. 1.3 million tiny files is a",
        "  per-file-cost workload, and four streams overlap the stalls that a",
        "  single rsync stream serialises.",
        "- `cb7` on mars and freya is only 1.16-1.24x. Bulk volume on a capable",
