        "",
        "### The orion cb7 result is mostly about `-z`, not about xsync",
        "",
        "The 7.82x headline (1676.2 s against 214.5 s) is the largest number in",
        "this matrix and the most easily over-read. A control run isolates it:",
        "",
        "| manga to | `rsync -a` | `rsync -az` | cost of `-z` |",
        "|---|---:|---:|---:|",
        "| mars | 36.4 s | 37.9 s | +4% |",
        "| orion | 36.8 s | 107.0 s | **+191%** |",
        "",
        "**Without `-z`, rsync to orion is exactly as fast as to mars** (36.8",
        "against 36.4). So `-z` is nearly free on mars and catastrophic on the",
        "Pi, and that single flag accounts for most of orion's deficit in every",
        "row above.",
        "",
        "These were ruled out as the cause -- all are equivalent between mars and",
        "orion: link (both switched gigabit, single-connection SSH measured at",
        "100 and 108 MiB/s), RTT (0.95 ms against 1.17 ms), negotiated SSH cipher",
        "(aes128-gcm both), rsync version (3.4.4 both ends), and destination disk.",
        "",
        "The mechanism is **not** established. The obvious explanation --",
        "receiver-side decompression saturating a Pi core -- is not supported by",
        "measurement: during `rsync -az` to orion nothing is CPU-saturated (rsync",
        "~5% of one core, sshd ~25%, over 90% of the box idle). Compression",
        "happens on the sender, which is the same Mac for every host, so a",
        "sender-side explanation cannot produce a per-host difference either.",
        "Something about how `-z` interacts with this receiver remains unexplained",
        "and is worth its own investigation.",
        "",
        "The honest summary of that cell: **`rsync -az` is 7.82x slower than",
        "`xs --streams 4` to a Raspberry Pi**, which is true and reproducible",
